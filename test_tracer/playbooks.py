"""
Generates the Ansible playbooks that implement the capture / harvest phases.

netlab already generates ``hosts.yml`` and ``ansible.cfg`` in the lab
directory; the generated playbooks are written to ``<lab-dir>/scenario-<name>/``
and are meant to be run from the lab directory (so ``ansible.cfg`` and the
inventory are picked up automatically).

Playbooks:

* ``scenario_capture_start.yml`` -- start background ``tcpdump`` (or
  ``tshark``) processes on the capture interfaces
* ``scenario_capture_stop.yml``  -- stop the background captures
* ``scenario_fetch.yml``         -- ``fetch`` the PCAP files into
  ``results/``
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List

import yaml

from .scenario import CaptureSpec


@dataclass
class CaptureEntry:
    """Interface data resolved from host_vars for a capture request."""

    node: str
    ifname: str


def resolve_capture_interfaces(lab_dir: Path, captures: List[CaptureSpec]) -> List[CaptureEntry]:
    """Resolve capture specs to concrete (node, ifname) pairs.

    Reads ``host_vars/<node>/topology.json`` generated by netlab to map a
    device-facing interface name to the actual container interface name. If
    the requested interface is not found in the node's interface list, it is
    used as-is (it may already be the container-level name).
    """
    entries: List[CaptureEntry] = []
    for cap in captures:
        ifname = cap.interface
        hv = lab_dir / "host_vars" / cap.node / "topology.json"
        if hv.exists():
            data = yaml.safe_load(hv.read_text()) or {}
            for intf in data.get("interfaces", []):
                if intf.get("ifname") == cap.interface:
                    ifname = intf["ifname"]
                    break
        entries.append(CaptureEntry(node=cap.node, ifname=ifname))
    return entries


def _dump(doc) -> str:
    # A playbook must be a *list* of plays.
    if isinstance(doc, dict):
        doc = [doc]
    return yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=1000)


def _ensure_tcpdump_task() -> dict:
    """Install tcpdump if missing (base OS images usually lack it)."""
    return {
        "name": "ensure tcpdump is installed",
        "ansible.builtin.shell": (
            "command -v tcpdump >/dev/null 2>&1 && echo present || "
            "{ apt-get update -qq && apt-get install -y -qq tcpdump; } >/tmp/ensure_tcpdump.log 2>&1"
        ),
        "ignore_errors": True,
    }


def _bootstrap_python_task() -> dict:
    """Install python3 if missing.

    Ansible modules (including ``shell``) need an interpreter on the target,
    but minimal OS images have none. ``raw`` is executed without a remote
    interpreter, so it can do the bootstrap.
    """
    return {
        "name": "bootstrap python3 (required by Ansible modules)",
        "ansible.builtin.raw": (
            "(apt-get update -qq && "
            "DEBIAN_FRONTEND=noninteractive apt-get install -y -qq python3) "
            ">/tmp/apt_bootstrap.log 2>&1"
        ),
        "ignore_errors": True,
    }


def _capture_start_playbook(captures: List[CaptureSpec], entries: List[CaptureEntry]) -> str:
    tasks = [_bootstrap_python_task()]
    for cap, entry in zip(captures, entries):
        tasks.append(_ensure_tcpdump_task())
        local_out = f"/tmp/{cap.out_name()}"
        bpf = f" -f \"{' '.join(cap.filter.split())}\"" if cap.filter else ""
        count_arg = f" -c {cap.count}" if cap.count else ""
        if cap.seconds:
            # Bounded capture: runs for `seconds`, then exits on its own.
            cmd = f"timeout -s TERM {cap.seconds} tcpdump -i {entry.ifname}{count_arg}{bpf} -s 0 -w {local_out}"
            tasks.append({
                "name": f"start capture on {cap.node}/{entry.ifname} (bounded {cap.seconds}s)",
                "ansible.builtin.shell": cmd,
            })
        else:
            cmd = (
                f"setsid nohup tcpdump -i {entry.ifname}{count_arg}{bpf} -s 0 "
                f"-w {local_out} >/tmp/capture.{entry.ifname}.log 2>&1 < /dev/null &"
                f"echo $! > /tmp/capture.{entry.ifname}.pid"
            )
            tasks.append({
                "name": f"start background capture on {cap.node}/{entry.ifname}",
                "ansible.builtin.shell": cmd,
            })
    playbook: Dict = {
        "hosts": sorted({c.node for c in captures}),
        "gather_facts": False,
        "tasks": tasks,
    }
    return _dump(playbook)


def _capture_stop_playbook(captures: List[CaptureSpec], entries: List[CaptureEntry]) -> str:
    tasks = []
    for cap, entry in zip(captures, entries):
        if cap.seconds or cap.count:
            continue  # bounded captures finish on their own
        tasks.append({
            "name": f"stop capture on {cap.node}/{entry.ifname}",
            "ansible.builtin.shell": (
                f"kill $(cat /tmp/capture.{entry.ifname}.pid) 2>/dev/null; "
                f"rm -f /tmp/capture.{entry.ifname}.pid"
            ),
            "ignore_errors": True,
        })
    playbook: Dict = {"hosts": sorted({e.node for e in entries}), "gather_facts": False, "tasks": tasks}
    return _dump(playbook)


def _fetch_playbook(captures: List[CaptureSpec]) -> str:
    tasks = []
    for cap in captures:
        tasks.append({
            "name": f"fetch {cap.out_name()} from {cap.node}",
            "ansible.builtin.fetch": {
                "src": f"/tmp/{cap.out_name()}",
                "dest": f"results/{cap.out_name()}",
                "flat": True,
            },
            "ignore_errors": True,
        })
    playbook: Dict = {"hosts": sorted({c.node for c in captures}), "gather_facts": False, "tasks": tasks}
    return _dump(playbook)


def generate_playbooks(work_dir: Path, name: str, captures: List[CaptureSpec]) -> Dict[str, Path]:
    """Write generated playbooks into ``work_dir``; return filename -> path."""
    work_dir.mkdir(parents=True, exist_ok=True)
    entries = resolve_capture_interfaces(work_dir.parent, captures)
    files = {
        "scenario_capture_start.yml": _capture_start_playbook(captures, entries),
        "scenario_capture_stop.yml": _capture_stop_playbook(captures, entries),
        "scenario_fetch.yml": _fetch_playbook(captures),
    }
    out = {}
    for fname, content in files.items():
        p = work_dir / fname
        p.write_text(content)
        out[fname] = p
    return out
